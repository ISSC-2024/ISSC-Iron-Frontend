/**
 * 检查是否满足评估体系演示条件
 * @param evaluationData 评估数据
 * @returns 如果满足演示条件返回演示配置，否则返回 null
 */
export const checkEvaluationDemoCondition = (evaluationData: any): EvaluationDemoConfig | null => {
  if (!DEMO_ENABLED) return null

  // 检查专家ID是否为2
  const hasExpertId2 = evaluationData.experts?.some((expert: any) => expert.id === '2')
  if (!hasExpertId2) return null

  // 检查智能评价工具是否只选中了多智能体辩论评价
  const tools = evaluationData.tools || []
  const debateTool = tools.find((tool: any) => tool.id === 'debate')
  const autoIndicatorsTool = tools.find((tool: any) => tool.id === 'auto_indicators')
  const adversarialTool = tools.find((tool: any) => tool.id === 'adversarial')

  // 只有多智能体辩论评价被启用，其他工具都未启用
  const onlyDebateEnabled =
    debateTool?.enabled === true && autoIndicatorsTool?.enabled !== true && adversarialTool?.enabled !== true

  if (!onlyDebateEnabled) return null

  // 评价指标体系保持默认（这里简化检查，实际可以更详细地验证指标结构）
  // 如果需要更严格的检查，可以比较指标结构与默认结构是否一致

  return EVALUATION_DEMO_CONFIG
}

/**
 * 处理评估体系演示
 * @param evaluationData 评估数据
 * @param demoConfig 演示配置
 * @returns 演示响应结果
 */
export const handleEvaluationDemo = async (
  _evaluationData: any,
  demoConfig: EvaluationDemoConfig,
): Promise<{ evalResultMarkdown: string }> => {
  // 计算随机延时
  const randomDelay = Math.floor(Math.random() * (demoConfig.maxDelay - demoConfig.minDelay)) + demoConfig.minDelay

  // 延时模拟
  await new Promise((resolve) => setTimeout(resolve, randomDelay))

  return {
    evalResultMarkdown: demoConfig.evalResultMarkdown,
  }
}
